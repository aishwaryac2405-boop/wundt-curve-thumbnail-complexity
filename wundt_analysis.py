def load_image(path):
    img = cv2.imread(path)
    if img is None:
        return None
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    return img

def shannon_entropy(img):
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    hist, _ = np.histogram(gray.flatten(), bins=256, density=True)
    hist = hist[hist > 0]
    return -np.sum(hist * np.log2(hist))

def edge_entropy(img, grid_size=10):
    gray = rgb2gray(img)
    edges = sobel(gray)
    h, w = edges.shape
    gh, gw = h//grid_size, w//grid_size
    counts = []
    for i in range(grid_size):
        for j in range(grid_size):
            cell = edges[i*gh:(i+1)*gh, j*gw:(j+1)*gw]
            counts.append(np.sum(cell))
    hist, _ = np.histogram(counts, bins=20, density=True)
    hist = hist[hist > 0]
    return -np.sum(hist * np.log(hist))

def saliency_entropy(img):
    saliency = cv2.saliency.StaticSaliencySpectralResidual_create()
    success, saliencyMap = saliency.computeSaliency(img)
    saliencyMap = (saliencyMap * 255).astype("uint8")
    hist, _ = np.histogram(saliencyMap.flatten(), bins=50, density=True)
    hist = hist[hist > 0]
    return -np.sum(hist * np.log(hist))

yolo_model = YOLO("yolov8n.pt")
def object_entropy(img, grid_size=5):
    results = yolo_model(img, verbose=False)[0]
    if results.boxes is None:
        return 0.0
    boxes = results.boxes.xyxy.cpu().numpy()
    h, w, _ = img.shape
    grid = np.zeros((grid_size, grid_size))
    for box in boxes:
        x1,y1,x2,y2 = box
        cx = int(((x1+x2)/2)/w * grid_size)
        cy = int(((y1+y2)/2)/h * grid_size)
        cx = np.clip(cx,0,grid_size-1)
        cy = np.clip(cy,0,grid_size-1)
        grid[cy,cx] += 1
    hist = grid.flatten()
    hist = hist / (np.sum(hist)+1e-9)
    hist = hist[hist>0]
    return -np.sum(hist * np.log(hist))

def color_entropy(img):
    hsv = rgb2hsv(img)
    h = hsv[:,:,0]
    hist, _ = np.histogram(h.flatten(), bins=30, density=True)
    hist = hist[hist>0]
    return -np.sum(hist * np.log(hist))

def thumbnail_entropy(img):
    return {
        "edge": edge_entropy(img),
        "saliency": saliency_entropy(img),
        "object": object_entropy(img),
        "color": color_entropy(img)
    }

def process_dataset(thumbnail_folder, meta_df):
    data = []
    for _, row in meta_df.iterrows():
        fname = str(row["file_name"]).strip()
        path = os.path.join(thumbnail_folder, f"{fname}.jpg")
        img = load_image(path)
        if img is not None:
            E = thumbnail_entropy(img)
            data.append({
                "file_name": fname,
                "view_count": row["view_count"],
                "channel_name": row["channel_name"],
                "subscriber_count": row["subscriber_count"],
                "viral_ratio": row["viral_ratio"],
                # "video_Link": row["video_link"],
                **E
            })
    return pd.DataFrame(data)
